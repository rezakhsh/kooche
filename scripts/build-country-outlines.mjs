// Draws the outline maps on listing pages: each country's states as simplified SVG paths, written
// to src/modules/listings/outline-data.ts. Input is Natural Earth's admin-1 file (public domain):
// https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson
//
//   node scripts/build-country-outlines.mjs /path/to/ne_10m_admin_1_states_provinces.geojson DE AT
//
// Projection: equirectangular, longitudes scaled by cos(middle latitude), 400 units wide. The
// same numbers go into the output, so outline-map.ts can place a listing's point on the drawing.

import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, ...codes] = process.argv;
if (!input || codes.length === 0) {
  console.error('usage: node scripts/build-country-outlines.mjs <admin1.geojson> DE AT …');
  process.exit(1);
}

const WIDTH = 400;
const TOLERANCE = 1; // drawing units: about half a pixel at the size shown (~200 px wide)
const MIN_AREA = 4; // islands smaller than this (square units) are left out

/** Douglas–Peucker on one ring of [x, y] points */
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const len = Math.hypot(bx - ax, by - ay);
    let max = 0;
    let index = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      // A closed ring starts and ends on the same point: measure from that point instead
      const d = len === 0 ? Math.hypot(px - ax, py - ay) : Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / len;
      if (d > max) [max, index] = [d, i];
    }
    if (max > tolerance) {
      keep[index] = 1;
      stack.push([a, index], [index, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (ring) => Math.abs(ring.reduce((s, [x, y], i) => {
  const [nx, ny] = ring[(i + 1) % ring.length];
  return s + x * ny - nx * y;
}, 0)) / 2;

const geo = JSON.parse(readFileSync(input, 'utf8'));
const out = {};
for (const code of codes) {
  const features = geo.features.filter((f) => f.properties.iso_a2 === code);
  if (features.length === 0) throw new Error(`No states for ${code}`);
  const polygons = (f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates);
  const all = features.flatMap((f) => polygons(f).flatMap((p) => p.flat()));
  const minLng = Math.min(...all.map((c) => c[0]));
  const maxLng = Math.max(...all.map((c) => c[0]));
  const minLat = Math.min(...all.map((c) => c[1]));
  const maxLat = Math.max(...all.map((c) => c[1]));
  const k = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
  const scale = WIDTH / ((maxLng - minLng) * k);
  const project = ([lng, lat]) => [(lng - minLng) * k * scale, (maxLat - lat) * scale];
  const r1 = (n) => Math.round(n * 10) / 10;

  const states = features
    .sort((a, b) => (a.properties.iso_3166_2 < b.properties.iso_3166_2 ? -1 : 1))
    .map((f) =>
      polygons(f)
        .map((poly) => poly[0].map(project))
        .filter((ring) => area(ring) >= MIN_AREA)
        .map((ring) => simplify(ring, TOLERANCE))
        .map((ring) => 'M' + ring.map(([x, y]) => `${r1(x)} ${r1(y)}`).join('L') + 'Z')
        .join(''),
    )
    .filter(Boolean);

  out[code] = {
    width: WIDTH,
    height: Math.ceil((maxLat - minLat) * scale),
    projection: { minLng, maxLat, k, scale },
    states,
  };
}

const target = new URL('../src/modules/listings/outline-data.ts', import.meta.url);
writeFileSync(
  target,
  `// Generated by scripts/build-country-outlines.mjs from Natural Earth (public domain). Do not edit.\n\n` +
    `export const OUTLINES: Record<string, { width: number; height: number; projection: { minLng: number; maxLat: number; k: number; scale: number }; states: string[] }> = ${JSON.stringify(out)};\n`,
);
for (const [code, o] of Object.entries(out)) {
  console.log(`${code}: ${o.states.length} states, ${o.width}×${o.height}, ${o.states.join('').length} bytes of paths`);
}
